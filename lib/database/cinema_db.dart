import 'package:path/path.dart';
import 'package:southsea_cinema/models/booking.dart';
import 'package:sqflite/sqflite.dart';

// Manages the SQLite database for cinema bookings.
class CinemaDatabase {
  // Private constructor so we use one shared database helper.
  CinemaDatabase._internal();

  // Shared instance used throughout the app.
  static final CinemaDatabase instance = CinemaDatabase._internal();

  // Stores the open database connection.
  static Database? _database;

  // Allows tests to supply their own database.
  void setDatabase(Database? db) {
    _database = db;
  }

  // Returns the existing database or opens it if needed.
  Future<Database> get database async {
    final Database? cachedDatabase = _database;

    if (cachedDatabase != null) {
      return cachedDatabase;
    }

    final Database db = await _initDB('cinema_data.db');
    _database = db;
    return db;
  }

  // Opens the database in the app's database folder.
  Future<Database> _initDB(String fileName) async {
    final String folder = await getDatabasesPath();
    final String filePath = join(folder, fileName);

    final Database db = await openDatabase(
      filePath,
      version: 1,
      onCreate: _createDB,
    );

    return db;
  }

  // Creates the bookings table with the required columns.
  Future<void> createTables(Database db, int version) async {
    await db.execute('''
      CREATE TABLE IF NOT EXISTS bookings (
        id INTEGER PRIMARY KEY AUTOINCREMENT,
        booking_number INTEGER NOT NULL,
        summary TEXT NOT NULL,
        total REAL NOT NULL,
        date TEXT NOT NULL
      )
    ''');
  }

  // Creates the bookings table and adds sample bookings.
  // This method only runs when the database is first created.
  Future<void> _createDB(Database db, int version) async {
    // Create the bookings table.
    await createTables(db, version);

    // Add the first sample cinema booking.
    await db.insert('bookings', <String, Object?>{
      'booking_number': 1003,
      'summary': '2 x Adult Tickets',
      'total': 16.50,
      'date': '18/04/2026 12:45',
    });

    // Add the second sample cinema booking.
    await db.insert('bookings', <String, Object?>{
      'booking_number': 1002,
      'summary': '1 x Student Ticket',
      'total': 6.00,
      'date': '02/03/2026 18:10',
    });

    // Add the third sample cinema booking.
    await db.insert('bookings', <String, Object?>{
      'booking_number': 1001,
      'summary': '3 x Adult Tickets',
      'total': 24.00,
      'date': '11/01/2026 13:02',
    });
  }

  // Saves a new booking in the SQLite database.
  // Returns the ID generated by SQLite.
  Future<int> insertBooking(Booking booking) async {
    // Open the database.
    final Database db = await database;

    // Convert the Booking into a Map and insert it.
    final int id = await db.insert(
      'bookings',
      booking.toMap(),
    );

    return id;
  }

  // Gets all bookings from the SQLite database.
  Future<List<Booking>> getAllBookings() async {
    // Open the database.
    final Database db = await database;

    // Read bookings, with the newest booking number first.
    final List<Map<String, Object?>> rows = await db.query(
      'bookings',
      orderBy: 'booking_number DESC',
    );

    // Convert each database row into a Booking object.
    final List<Booking> bookings = rows.map((row) {
      return Booking.fromMap(row);
    }).toList();

    return bookings;
  }

  // Finds the next available cinema booking number.
  Future<int> nextBookingNumber() async {
    // Open the SQLite database.
    final Database db = await database;

    // Find the highest booking number currently saved.
    final List<Map<String, Object?>> result = await db.rawQuery(
      'SELECT MAX(booking_number) AS max_number FROM bookings',
    );

    // Get the highest booking number from the result.
    final int? maxNumber = result.first['max_number'] as int?;

    // Start at 1001 if there are no bookings yet.
    // Otherwise, increase the highest booking number by 1.
    return (maxNumber ?? 1000) + 1;
  }

  // Closes the SQLite database connection.
  Future<void> close() async {
    // Get the currently open database.
    final Database? db = _database;

    // Clear the saved connection.
    _database = null;

    // Close the database if one is open.
    if (db != null) {
      await db.close();
    }
  }
}
